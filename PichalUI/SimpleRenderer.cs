float3 ApplyMnemos(Texture2D tex, SamplerState samp, float2 uv, float2 texSize) {
    float2 px = 1.0 / texSize;
    
    // 1. Calcular o Gradiente do Pixel (Para saber qual filtro usar)
    // Usamos uma versão simplificada do Sobel para ser rápido
    float3 c = tex.SampleLevel(samp, uv, 0).rgb;
    float lumaC = dot(c, float3(0.299, 0.587, 0.114));
    
    float lumaN = dot(tex.SampleLevel(samp, uv + float2(0, -px.y), 0).rgb, float3(0.299, 0.587, 0.114));
    float lumaW = dot(tex.SampleLevel(samp, uv + float2(-px.x, 0), 0).rgb, float3(0.299, 0.587, 0.114));
    
    // Gradientes simples
    float gy = lumaN - lumaC;
    float gx = lumaW - lumaC;
    
    // 2. Calcular o Ângulo (Hashing)
    // A matemática tem de ser IGUAL à do Python
    float angle = atan2(gy, gx);
    if (angle < 0) angle += 3.14159265; // Pi
    
    // Converter para Índice (0 a 23)
    int angle_idx = int((angle / 3.14159265) * 24.0) % 24;
    
    // 3. Aplicação do Filtro (Convolução)
    float3 finalColor = float3(0, 0, 0);
    int center = 5; // Metade de 11
    
    // Loop 11x11 (Pesado! Se ficar lento, reduzimos para 5x5 no Python)
    [unroll] // Tenta desenrolar para performance
    for (int y = -5; y <= 5; y++) {
        for (int x = -5; x <= 5; x++) {
            
            // Onde ler na textura
            float2 offset = float2(x, y) * px;
            float3 pixel = tex.SampleLevel(samp, uv + offset, 0).rgb;
            
            // Qual peso usar (mapa 1D)
            int weight_idx = (y + 5) * 11 + (x + 5);
            float weight = mnemos_weights[angle_idx][weight_idx];
            
            finalColor += pixel * weight;
        }
    }
    
    return finalColor;
}

