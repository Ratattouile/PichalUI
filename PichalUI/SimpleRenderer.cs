// Bicubic Standard (Usado pelo Mitchell)
float3 BicubicSample(Texture2D tex, SamplerState samp, float2 uv, float2 texSize) {
    float2 pixelPos = uv * texSize;
    float2 tc = floor(pixelPos - 0.5) + 0.5;
    float2 f = pixelPos - tc;
    
    float2 f2 = f * f;
    float2 f3 = f2 * f;
    
    float2 w0 = f2 - 0.5 * (f3 + f);
    float2 w1 = 1.5 * f3 - 2.5 * f2 + 1.0;
    float2 w2 = -1.5 * f3 + 2.0 * f2 + 0.5 * f;
    float2 w3 = 0.5 * (f3 - f2);
    
    float2 s0 = w0 + w1;
    float2 s1 = w2 + w3;
    float2 f0 = w1 / s0;
    float2 f1 = w3 / s1;
    
    float2 t0 = tc - 1.0 + f0;
    float2 t1 = tc + 1.0 + f1;
    
    float2 invSize = 1.0 / texSize;
    
    float3 c0 = tex.SampleLevel(samp, float2(t0.x, t0.y) * invSize, 0).rgb;
    float3 c1 = tex.SampleLevel(samp, float2(t1.x, t0.y) * invSize, 0).rgb;
    float3 c2 = tex.SampleLevel(samp, float2(t0.x, t1.y) * invSize, 0).rgb;
    float3 c3 = tex.SampleLevel(samp, float2(t1.x, t1.y) * invSize, 0).rgb;
    
    return (c0*s0.x*s0.y + c1*s1.x*s0.y + c2*s0.x*s1.y + c3*s1.x*s1.y) / ((s0.x+s1.x)*(s0.y+s1.y));
}

// Motor: Catmull-Rom Suave
float3 SampleSmoothCatmull(Texture2D tex, SamplerState samp, float2 uv, float2 texSize) {
    float2 pixelPos = uv * texSize;
    float2 tc = floor(pixelPos - 0.5) + 0.5;
    float2 f = pixelPos - tc;
    
    float2 w0 = f * f * (0.5 - 0.5 * f);
    float2 w1 = 1.0 + f * f * (-2.5 + 1.5 * f);
    float2 w2 = f * (0.5 + f * (2.0 - 1.5 * f));
    float2 w3 = f * f * (-0.5 + 0.5 * f);
    
    float2 s0 = w0 + w1;
    float2 s1 = w2 + w3;
    float2 f0 = w1 / s0;
    float2 f1 = w3 / s1;
    float2 t0 = tc - 1.0 + f0;
    float2 t1 = tc + 1.0 + f1;
    float2 invSize = 1.0 / texSize;
    
    return (tex.SampleLevel(samp, float2(t0.x, t0.y) * invSize, 0).rgb * s0.x * s0.y +
            tex.SampleLevel(samp, float2(t1.x, t0.y) * invSize, 0).rgb * s1.x * s0.y +
            tex.SampleLevel(samp, float2(t0.x, t1.y) * invSize, 0).rgb * s0.x * s1.y +
            tex.SampleLevel(samp, float2(t1.x, t1.y) * invSize, 0).rgb * s1.x * s1.y) / ((s0.x + s1.x) * (s0.y + s1.y));
}

