// SharpBilinear
float3 SampleSharpBilinear(Texture2D tex, SamplerState samp, float2 uv, float2 texSize){
    float2 center = uv * texSize - 0.5;
    float2 f = frac(center);
    f = f * f * (3.0 - 2.0 * f);
    float2 invSize = 1.0 / texSize;
    float2 tc = (floor(center) + 0.5) * invSize;

    float3 p00 = tex.SampleLevel(samp, tc, 0).rgb;
    float3 p10 = tex.SampleLevel(samp, tc + float2(invSize.x, 0), 0).rgb;
    float3 p01 = tex.SampleLevel(samp, tc + float2(0, invSize.y), 0).rgb;
    float3 p11 = tex.SampleLevel(samp, tc + float2(invSize.x, invSize.y), 0).rgb;

    return lerp(lerp(p00, p10, f.x), lerp(p01, p11, f.x), f.y);
}

// RoboCrisp (Mantemos aqui caso queiras voltar a usar)
float3 SampleRoboCrisp(Texture2D tex, SamplerState samp, float2 uv, float2 texSize){
    float2 px = 1.0 / texSize;
    float3 c = tex.SampleLevel(samp, uv, 0).rgb;

    float3 n = tex.SampleLevel(samp, uv + float2(0, -px.y), 0).rgb;
    float3 s = tex.SampleLevel(samp, uv + float2(0, px.y), 0).rgb;
    float3 w = tex.SampleLevel(samp, uv + float2(-px.x, 0), 0).rgb;
    float3 e = tex.SampleLevel(samp, uv + float2(px.x, 0), 0).rgb;

    float3 blur = (n + s + w + e) * 0.25;
    float3 diff = c - blur;
    return c + diff * 1.3;
}

// Função auxiliar Lanczos
float LanczosWeight(float x) {
    float PI = 3.14159265;
    if (x == 0.0) return 1.0;
    if (x >= 2.0) return 0.0;
    return (sin(PI * x) / (PI * x)) * (sin(PI * x / 2.0) / (PI * x / 2.0));
}

// Motor: LANCZOS
float3 SampleLanczos(Texture2D tex, SamplerState samp, float2 uv, float2 texSize) {
    float2 pixelPos = uv * texSize;
    float2 tc = floor(pixelPos - 0.5) + 0.5;
    float2 f = pixelPos - tc;
    
    float wx0 = LanczosWeight(1.0 + f.x); float wx1 = LanczosWeight(f.x);
    float wx2 = LanczosWeight(1.0 - f.x); float wx3 = LanczosWeight(2.0 - f.x);
    
    float wy0 = LanczosWeight(1.0 + f.y); float wy1 = LanczosWeight(f.y);
    float wy2 = LanczosWeight(1.0 - f.y); float wy3 = LanczosWeight(2.0 - f.y);

    float2 w0 = float2(wx1, wy1);
    float2 w1 = float2(wx2, wy2);
    
    float2 s0 = w0 + w1; 
    float2 f0 = w1 / s0; 
    float2 t0 = tc - 0.5 + f0;
    
    float2 invSize = 1.0 / texSize;
    float3 c0 = tex.SampleLevel(samp, (tc + float2(-0.5, -0.5)) * invSize, 0).rgb;
    float3 c1 = tex.SampleLevel(samp, (tc + float2( 0.5, -0.5)) * invSize, 0).rgb;
    float3 c2 = tex.SampleLevel(samp, (tc + float2(-0.5,  0.5)) * invSize, 0).rgb;
    float3 c3 = tex.SampleLevel(samp, (tc + float2( 0.5,  0.5)) * invSize, 0).rgb;
    
    return BicubicSample(tex, samp, uv, texSize) * 1.1 - 0.1;
}

// Motor: HERMITE
float3 SampleHermite(Texture2D tex, SamplerState samp, float2 uv, float2 texSize) {
    float2 pixelPos = uv * texSize;
    float2 tc = floor(pixelPos - 0.5) + 0.5;
    float2 f = pixelPos - tc;

    float2 w = f * f * (3.0 - 2.0 * f);
    float2 invSize = 1.0 / texSize;
    
    float3 c00 = tex.SampleLevel(samp, (tc + float2(-0.5, -0.5)) * invSize, 0).rgb;
    float3 c10 = tex.SampleLevel(samp, (tc + float2( 0.5, -0.5)) * invSize, 0).rgb;
    float3 c01 = tex.SampleLevel(samp, (tc + float2(-0.5,  0.5)) * invSize, 0).rgb;
    float3 c11 = tex.SampleLevel(samp, (tc + float2( 0.5,  0.5)) * invSize, 0).rgb;

    float3 top = lerp(c00, c10, w.x);
    float3 bot = lerp(c01, c11, w.x);
    return lerp(top, bot, w.y);
}

// Motor: SUPER-RES
float3 SampleSuperRes(Texture2D tex, SamplerState samp, float2 uv, float2 texSize) {
    float2 d = (1.0 / texSize) * 0.25; 
    float3 s1 = tex.SampleLevel(samp, uv + float2( d.x,  d.y), 0).rgb;
    float3 s2 = tex.SampleLevel(samp, uv + float2(-d.x, -d.y), 0).rgb;
    float3 s3 = tex.SampleLevel(samp, uv + float2(-d.x,  d.y), 0).rgb;
    float3 s4 = tex.SampleLevel(samp, uv + float2( d.x, -d.y), 0).rgb;
    return (s1 + s2 + s3 + s4) * 0.25;
}

// [NOVO] MOTOR: CAS (Fix - Sem erro de sqrt)
float3 SampleCAS(Texture2D tex, SamplerState samp, float2 uv, float2 texSize, float sharpStrength) {
    float2 px = 1.0 / texSize;
    
    float3 n = tex.SampleLevel(samp, uv + float2(0, -px.y), 0).rgb;
    float3 s = tex.SampleLevel(samp, uv + float2(0, px.y), 0).rgb;
    float3 w = tex.SampleLevel(samp, uv + float2(-px.x, 0), 0).rgb;
    float3 e = tex.SampleLevel(samp, uv + float2(px.x, 0), 0).rgb;
    float3 c = tex.SampleLevel(samp, uv, 0).rgb;
    
    // CAS Corrigido para não crashar
    float3 minRGB = min(c, min(min(n, s), min(w, e)));
    float3 maxRGB = max(c, max(max(n, s), max(w, e)));
    
    // Cálculo de Amount seguro
    float peak = -1.0 / lerp(8.0, 5.0, clamp(sharpStrength, 0.0, 1.0));
    float3 wRGB = float3(peak, peak, peak);
    float3 rcpWeight = 1.0 / (1.0 + 4.0 * wRGB);
    
    float3 final = (c + (n + s + w + e) * wRGB) * rcpWeight;
    
    // Mistura linear para controlar a força
    return lerp(c, final, sharpStrength);
}

float3 CleanSpeckles(float3 c, float3 n, float3 s, float3 w, float3 e){
    float3 minN = min(min(n, s), min(w, e));
    float3 maxN = max(max(n, s), max(w, e));

    return clamp(c, minN, maxN);
}

