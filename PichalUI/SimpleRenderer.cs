        public void Draw(ID3D11ShaderResourceView textureView, NativeUtils.RECT gameRect, int screenWidth, int screenHeight)
        {
            if (textureView == null || screenWidth == 0 || screenHeight == 0) return;

            // --- ATUALIZA A RESOLUÇÃO PARA O SHADER ---
            // Isto corrige o "Deep Fried" porque o shader passa a saber o tamanho real.
            var data = new ScreenBuffer
            {
                Width = (float)screenWidth,
                Height = (float)screenHeight,
                Padding1 = 0,
                Padding2 = 0
            };

            unsafe
            {
                // Mapeia a memória da GPU para escrevermos nela
                var mapped = _context.Map(_constantBuffer, 0, MapMode.WriteDiscard, Vortice.Direct3D11.MapFlags.None);
                Unsafe.Copy(mapped.DataPointer.ToPointer(), ref data);
                _context.Unmap(_constantBuffer, 0);
            }

            // Envia o Buffer para o Slot 0 (b0 no Shader)
            _context.PSSetConstantBuffers(0, new[] { _constantBuffer });

            // --- CÁLCULO DE COORDENADAS (O teu código antigo) ---
            float leftU = (float)gameRect.Left / screenWidth;
            float topV = (float)gameRect.Top / screenHeight;
            float rightU = (float)gameRect.Right / screenWidth;
            float bottomV = (float)gameRect.Bottom / screenHeight;

            if (rightU <= leftU) rightU = leftU + 0.001f;
            if (bottomV <= topV) bottomV = topV + 0.001f;

            var vertices = new[]
            {
                new Vertex(new Vector3(-1, 1, 0), new Vector2(leftU, topV)),
                new Vertex(new Vector3(1, 1, 0), new Vector2(rightU, topV)),
                new Vertex(new Vector3(-1, -1, 0), new Vector2(leftU, bottomV)),
                new Vertex(new Vector3(-1, -1, 0), new Vector2(leftU, bottomV)),
                new Vertex(new Vector3(1, 1, 0), new Vector2(rightU, topV)),
                new Vertex(new Vector3(1, -1, 0), new Vector2(rightU, bottomV)),
            };

            unsafe
            {
                var mapped = _context.Map(_vertexBuffer, 0, MapMode.WriteDiscard, Vortice.Direct3D11.MapFlags.None);
                fixed (Vertex* pVertices = vertices)
                {
                    Unsafe.CopyBlock(mapped.DataPointer.ToPointer(), pVertices, (uint)(Unsafe.SizeOf<Vertex>() * 6));
                }
                _context.Unmap(_vertexBuffer, 0);
            }

            _context.RSSetState(_rasterizerState);
            _context.IASetInputLayout(_inputLayout);
            _context.IASetPrimitiveTopology(PrimitiveTopology.TriangleList);

            uint stride = (uint)Unsafe.SizeOf<Vertex>();
            uint offset = 0;
            _context.IASetVertexBuffers(0, 1, new[] { _vertexBuffer }, new uint[] { stride }, new uint[] { offset });

            _context.VSSetShader(_vertexShader);
            _context.PSSetShader(_pixelShader);

            // LIGA OS RECURSOS
            _context.PSSetShaderResource(0, textureView);
            // IMPORTANTE: Envia os 2 samplers (Linear e Point)
            _context.PSSetSamplers(0, new[] { _samplerLinear, _samplerPoint });

            _context.Draw(6, 0);

            _context.PSSetShaderResource(0, null);
            _context.RSSetState(null);
        }

